const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { codexConfiguredProvider } = require('../../src/agents/codex-config-summary.cjs')

test('Codex summary follows the configured profile and never returns secret-like values', t => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'meldwork-codex-summary-'))
  t.after(() => fs.rmSync(home, { recursive: true, force: true }))
  const root = path.join(home, 'selected')
  fs.mkdirSync(root)
  const file = path.join(root, 'config.toml')
  fs.writeFileSync(file, "profile = 'work'\nmodel_provider = 'other'\n[profiles.work]\nmodel_provider = 'custom'\n")
  assert.equal(codexConfiguredProvider({ home, env: { CODEX_HOME: root } }), 'custom')
  fs.writeFileSync(file, "model_provider = 'openai'\n")
  assert.equal(codexConfiguredProvider({ home, env: { CODEX_HOME: root } }), 'openai')
  fs.writeFileSync(file, "model_provider = 'sk-12345678901234567890'\n")
  assert.equal(codexConfiguredProvider({ home, env: { CODEX_HOME: root } }), '')
  fs.writeFileSync(file, 'invalid = [')
  assert.equal(codexConfiguredProvider({ home, env: { CODEX_HOME: root } }), '')
})
