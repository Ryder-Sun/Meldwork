const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { hermesConfiguredProvider } = require('../../src/agents/hermes-config-summary.cjs')

test('Hermes configuration summary reads the selected provider without exposing credentials', t => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'meldwork-hermes-summary-'))
  t.after(() => fs.rmSync(home, { recursive: true, force: true }))
  const root = path.join(home, 'selected')
  fs.mkdirSync(root)
  const file = path.join(root, 'config.yaml')
  fs.writeFileSync(file, 'model:\n  provider: "custom:work"\n  api_key: secret-value\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root, HERMES_INFERENCE_PROVIDER: 'other' } }), 'custom:work')
  fs.writeFileSync(file, 'model:\n  provider: auto\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root } }), 'auto')
  fs.writeFileSync(file, 'model:\n  provider: auto\n  default:\n    provider: "custom:work"\n    model: chosen\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root } }), 'custom:work')
  fs.writeFileSync(file, 'provider: openrouter\nmodel: chosen\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root } }), 'openrouter')
  fs.writeFileSync(file, 'model:\n  provider: "sk-12345678901234567890"\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root } }), '')
  fs.writeFileSync(file, 'invalid: [')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root, HERMES_INFERENCE_PROVIDER: 'other' } }), '')
})
