const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { hermesConfiguredProvider } = require('../../src/agents/hermes-config-summary.cjs')

test('Hermes configuration summary reads the selected provider without exposing credentials', t => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'meldwork-hermes-summary-'))
  t.after(() => fs.rmSync(home, { recursive: true, force: true }))
  const root = path.join(home, 'selected')
  fs.mkdirSync(root)
  const file = path.join(root, 'config.yaml')
  fs.writeFileSync(file, 'model:\n  provider: "custom:work"\n  api_key: secret-value\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root, HERMES_INFERENCE_PROVIDER: 'other' } }), 'custom:work')
  fs.writeFileSync(file, 'model:\n  provider: auto\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root } }), 'auto')
  fs.writeFileSync(file, 'model:\n  provider: auto\n  default:\n    provider: "custom:work"\n    model: chosen\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root } }), 'custom:work')
  fs.writeFileSync(file, 'provider: openrouter\nmodel: chosen\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root } }), 'openrouter')
  fs.writeFileSync(file, 'model:\n  provider: 2070\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root } }), '2070')
  fs.writeFileSync(file, 'model:\n  provider: auto\n  default:\n    provider: 2070\n    model: chosen\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root } }), '2070')
  fs.writeFileSync(file, 'model:\n  provider: "sk-12345678901234567890"\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root } }), '')
  fs.writeFileSync(file, 'invalid: [')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: root, HERMES_INFERENCE_PROVIDER: 'other' } }), '')
})

test('Hermes summary reads the selected native environment provider without exposing other values', t => {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'meldwork-hermes-env-summary-'))
  t.after(() => fs.rmSync(home, { recursive: true, force: true }))
  fs.writeFileSync(path.join(home, '.env'), 'API_KEY=synthetic-secret\nexport HERMES_INFERENCE_PROVIDER="openrouter"\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: home } }), 'openrouter')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: home, HERMES_INFERENCE_PROVIDER: 'custom' } }), 'openrouter')
  fs.writeFileSync(path.join(home, '.env'), 'HERMES_INFERENCE_PROVIDER=\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: home, HERMES_INFERENCE_PROVIDER: 'custom' } }), '')
  fs.writeFileSync(path.join(home, '.env'), 'HERMES_INFERENCE_PROVIDER=${OTHER_PROVIDER}\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: home, HERMES_INFERENCE_PROVIDER: 'custom' } }), '')
  fs.writeFileSync(path.join(home, '.env'), 'SELECTED_PROVIDER=openrouter\nHERMES_INFERENCE_PROVIDER=${SELECTED_PROVIDER}\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: home, SELECTED_PROVIDER: 'stale' } }), 'openrouter')
  fs.writeFileSync(path.join(home, '.env'), 'HERMES_INFERENCE_PROVIDER=${UNSET_MELDWORK_PROVIDER:-custom:work}\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: home } }), 'custom:work')
  fs.writeFileSync(path.join(home, 'config.yaml'), 'model:\n  provider: anthropic\n')
  assert.equal(hermesConfiguredProvider({ home, env: { HERMES_HOME: home } }), 'anthropic')
})
